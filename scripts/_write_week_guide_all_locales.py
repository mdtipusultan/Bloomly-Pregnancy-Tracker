def write_locale(locale: str, data: dict[str, str]) -> int:
    missing = set(EXPECTED_KEYS) - set(data.keys())
    extra = set(data.keys()) - set(EXPECTED_KEYS)
    if missing:
        raise SystemExit(f"{locale}: missing keys: {sorted(missing)}")
    if extra:
        raise SystemExit(f"{locale}: extra keys: {sorted(extra)}")
    for key in ("weekGuide.development %lld", "weekGuide.momFeeling %lld"):
        if "%lld" not in data[key]:
            raise SystemExit(f"{locale}: {key} missing %lld")
    ordered = {k: data[k] for k in EXPECTED_KEYS}
    path = OUT / f"{locale}.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        json.dump(ordered, f, ensure_ascii=False, indent=2)
        f.write("\n")
    return len(ordered)


def main() -> None:
    created: list[tuple[str, int, str]] = []
    for locale, data in T.items():
        n = write_locale(locale, data)
        created.append((locale, n, "created"))
    for locale, patches in FIXES.items():
        path = OUT / f"{locale}.json"
        with path.open(encoding="utf-8") as f:
            data = json.load(f)
        data.update(patches)
        n = write_locale(locale, data)
        created.append((locale, n, "fixed"))
    for locale, n, action in sorted(created, key=lambda x: (x[2], x[0])):
        print(f"{action:7} {locale}.json  keys={n}")
    print(f"\nTotal: {len(created)} files written")


if __name__ == "__main__":
    main()
