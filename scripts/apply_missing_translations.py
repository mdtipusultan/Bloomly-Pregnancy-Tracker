FORMAT_SPEC_RE = re.compile(r"%(\d+\$)?[@lld]+")


def extract_format_specs(text: str) -> list[str]:
    return FORMAT_SPEC_RE.findall(text)


def format_specs_match(en_val: str, new_val: str) -> bool:
    """Compare format placeholders, allowing positional reorder (%1$@ vs %2$@)."""
    en_specs = sorted(FORMAT_SPEC_RE.findall(en_val))
    new_specs = sorted(FORMAT_SPEC_RE.findall(new_val))
    if en_specs == new_specs:
        return True
    en_plain = re.findall(r"%[@lld]+", en_val)
    new_plain = re.findall(r"%[@lld]+", new_val)
    return en_plain == new_plain and len(en_plain) == len(en_specs)


def coverage_stats(data: dict) -> dict[str, dict[str, int]]:
    strings = data["strings"]
    all_locales: set[str] = set()
    for entry in strings.values():
        all_locales.update(entry.get("localizations", {}).keys())

    stats: dict[str, dict[str, int]] = {}
    for lang in sorted(all_locales):
        translated = english_fallback = missing = 0
        for entry in strings.values():
            locs = entry.get("localizations", {})
            en_val = locs.get("en", {}).get("stringUnit", {}).get("value")
            if not en_val:
                continue
            lang_val = locs.get(lang, {}).get("stringUnit", {}).get("value")
            if not lang_val:
                missing += 1
            elif lang_val == en_val:
                english_fallback += 1
            else:
                translated += 1
        stats[lang] = {
            "translated": translated,
            "english_fallback": english_fallback,
            "missing": missing,
        }
    return stats


def print_coverage(stats: dict[str, dict[str, int]], title: str) -> None:
    print(f"\n=== {title} ===")
    for lang, counts in stats.items():
        total = counts["translated"] + counts["english_fallback"] + counts["missing"]
        pct = 100 * counts["translated"] / total if total else 0
        print(
            f"  {lang:8} translated={counts['translated']:3d}  "
            f"english={counts['english_fallback']:3d}  "
            f"missing={counts['missing']:3d}  "
            f"coverage={pct:5.1f}%"
        )


def apply_translations(data: dict) -> tuple[int, list[str]]:
    strings = data["strings"]
    updated = 0
    warnings: list[str] = []

    for key, entry in strings.items():
        locs = entry.setdefault("localizations", {})
        en_val = locs.get("en", {}).get("stringUnit", {}).get("value")
        if not en_val:
            continue

        for lang in TARGET_LANGS:
            lang_dict = TRANSLATIONS.get(lang, {})
            if key not in lang_dict:
                warnings.append(f"Missing translation: {lang}/{key}")
                continue

            new_val = lang_dict[key]
            current = locs.get(lang, {}).get("stringUnit", {}).get("value")

            if current != en_val and current is not None:
                continue

            if not format_specs_match(en_val, new_val):
                warnings.append(
                    f"Format specifier mismatch {lang}/{key}: "
                    f"en={extract_format_specs(en_val)!r} new={extract_format_specs(new_val)!r}"
                )
                continue

            locs[lang] = {
                "stringUnit": {
                    "state": "translated",
                    "value": new_val,
                }
            }
            updated += 1

    return updated, warnings


def verify_translations(data: dict | None = None) -> None:
    if data is None:
        data = json.loads(XCSTRINGS.read_text(encoding="utf-8"))
    english_keys = {
        key
        for key, entry in data["strings"].items()
        if entry.get("localizations", {}).get("en", {}).get("stringUnit", {}).get("value")
    }
    for lang in TARGET_LANGS:
        lang_dict = TRANSLATIONS[lang]
        missing = english_keys - set(lang_dict)
        extra = set(lang_dict) - english_keys
        if missing:
            print(f"ERROR: {lang} missing {len(missing)} keys: {sorted(missing)[:5]}...", file=sys.stderr)
            sys.exit(1)
        if extra:
            print(f"WARN: {lang} has {len(extra)} extra keys", file=sys.stderr)


def main() -> None:
    if not XCSTRINGS.exists():
        print(f"ERROR: {XCSTRINGS} not found", file=sys.stderr)
        sys.exit(1)

    for lang in TARGET_LANGS:
        json_path = LANG_DATA_DIR / f"{lang}.json"
        if not json_path.exists():
            print(f"ERROR: {json_path} not found", file=sys.stderr)
            sys.exit(1)

    data = json.loads(XCSTRINGS.read_text(encoding="utf-8"))
    verify_translations(data)
    before = coverage_stats(data)
    print_coverage(before, "Coverage BEFORE")

    updated, warnings = apply_translations(data)
    after = coverage_stats(data)
    print_coverage(after, "Coverage AFTER")

    XCSTRINGS.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )

    print(f"\nUpdated {updated} localization entries across {len(TARGET_LANGS)} languages.")
    if warnings:
        print(f"\nWarnings ({len(warnings)}):")
        for w in warnings[:20]:
            print(f"  - {w}")
        if len(warnings) > 20:
            print(f"  ... and {len(warnings) - 20} more")

    bn_samples = [
        ("tab.home", "হোম"),
        ("profile.title", "প্রোফাইল"),
        ("home.title", "হোম"),
        ("settings.language", "ভাষা"),
        ("language.bengali", "বাংলা"),
    ]
    print("\n=== Bengali verification (xcstrings) ===")
    for key, expected in bn_samples:
        val = (
            data["strings"][key]["localizations"]["bn"]["stringUnit"]["value"]
        )
        status = "OK" if val == expected else f"MISMATCH (got {val!r})"
        print(f"  {key}: {status}")


if __name__ == "__main__":
    main()
